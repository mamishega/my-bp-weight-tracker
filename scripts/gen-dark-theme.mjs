// Generates src/theme-dark.css: a dark theme made by mirroring each Tailwind
// colour scale (50<->950, 100<->900, ...) and mapping white to the dark card
// surface. Screen only — printing always uses the light theme.
import { readFileSync, writeFileSync } from 'node:fs';
const theme = readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const families = ['slate', 'teal', 'amber', 'red', 'emerald', 'sky', 'fuchsia', 'blue', 'orange', 'violet'];
const steps = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const val = (f, s) => {
  const m = new RegExp(`--color-${f}-${s}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`missing ${f}-${s}`);
  return m[1].trim();
};
const decl = [];
for (const f of families) steps.forEach((s, i) => decl.push(`--color-${f}-${s}: ${val(f, steps[steps.length - 1 - i])};`));
// Muted text (slate-400/500) must stay readable on dark surfaces (WCAG AA 4.5:1).
decl.push(`--color-slate-500: ${val('slate', 400)};`, `--color-slate-400: ${val('slate', 300)};`);
decl.push(`--color-white: oklch(23% 0.03 264);`); // card surface
decl.push(`--app-bg: oklch(17% 0.025 264);`); // page background (darker than cards)
decl.push(`--series-1: #3987e5; --series-2: #d95926; --series-3: #199e70; --series-ma: #9ec5f4;`);
decl.push(`--chart-grid: oklch(32% 0.03 264); --chart-axis: oklch(72% 0.02 264); --chart-ref: oklch(65% 0.02 264);`);
decl.push(`color-scheme: dark;`);
const block = decl.map((d) => `    ${d}`).join('\n');
const css = `/* Generated by scripts/gen-dark-theme.mjs — do not edit by hand. */
:root {
  --app-bg: #f5f7f9;
  /* Slightly darker muted text so it meets WCAG AA (4.5:1) on the page background too. */
  --color-slate-500: oklch(49% 0.041 257.3);
  --series-1: #2a78d6; --series-2: #eb6834; --series-3: #1baf7a; --series-ma: #0d366b;
  --chart-grid: #e2e8f0; --chart-axis: #475569; --chart-ref: #64748b;
}
@media screen {
  :root[data-theme='dark'] {
${block}
  }
}
@media screen and (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${block}
  }
}
`;
writeFileSync('src/theme-dark.css', css);
console.log('wrote src/theme-dark.css');
